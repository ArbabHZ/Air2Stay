import assert from 'node:assert/strict';
import fs from 'node:fs';
import { runScenario, getBridge } from '../prototype/engine.mjs';
import { decisionNote } from '../prototype/decision_tools.mjs';
import { proposalKey, proposalFingerprint, createProposalStore, priorityActions, stakeholderDraft, createProposalWorkspace } from '../prototype/proposal_workspace.mjs';

const data = JSON.parse(fs.readFileSync(new URL('../prototype/data/scenario_data.json', import.meta.url)));
const route = data.routes.find((row) => row.originKey === 'FRANCE' && row.month === 12);
const bridge = getBridge(data, route.originKey, route.month);
const inputs = { originKey: route.originKey, month: 12, extraFlights: 5, seatsPerFlight: Math.round(route.seatsPerFlight), loadFactor: route.loadFactor, p2pShare: route.p2pShare, conversionRate: data.defaults.captureRate, averageStay: bridge.reduce((sum, row) => sum + row.weight * row.averageStay, 0), eventUplift: 0, bridgeOverride: null };
const context = (values = inputs) => ({ inputs: { ...values }, result: runScenario(data, values), decision: decisionNote(data, values) });
const memory = new Map();
const storage = { getItem: (key) => memory.get(key), setItem: (key, value) => memory.set(key, value) };
const clock = () => new Date('2026-11-01T12:00:00Z');
const store = createProposalStore(storage, clock);
const ctx = context();
const key = proposalKey(inputs);
const before = JSON.stringify(ctx);
const saved = store.saveVersion(ctx, 'Airline discussion');
assert.equal(JSON.stringify(ctx), before, 'Saving does not alter calculation context');
saved.inputs.extraFlights = 99;
assert.equal(store.get(key).versions[0].inputs.extraFlights, 5, 'Saved snapshots cannot be mutated through return values');
const read = store.get(key);
read.versions[0].result.scenario.guestNights = -1;
assert.ok(store.get(key).versions[0].result.scenario.guestNights > 0, 'Stored results are immutable through read objects');
const savedVersion = store.get(key).versions[0];
assert.deepEqual(runScenario(data, savedVersion.inputs), savedVersion.result, 'Restoring exact inputs reproduces the snapshot');
assert.equal(proposalFingerprint(ctx), proposalFingerprint({ result: ctx.result, inputs: Object.fromEntries(Object.entries(inputs).reverse()) }), 'Property order cannot invalidate evidence');
assert.notEqual(proposalFingerprint(ctx), proposalFingerprint(context({ ...inputs, bridgeOverride: bridge })), 'Visitor mix is part of the exact plan identity');
assert.notEqual(proposalFingerprint(ctx), proposalFingerprint({ ...ctx, result: { ...ctx.result, baseline: { ...ctx.result.baseline, guestNights: 5 } } }), 'New source data invalidates earlier evidence');

store.addComment(ctx, 'Ask the airline to confirm the December schedule.');
store.addDecision(ctx, 'Investigate', 'Confirm bookings before committing to capacity.');
store.addDiscussion(ctx, 'user', 'How many nights does this add?');
store.addDiscussion(ctx, 'bot', 'Use the current estimate, then check the assumptions.', 'ai');
const november = context({ ...inputs, month: 11 });
const india = context({ ...inputs, originKey: 'INDIA' });
assert.equal(store.get(proposalKey(november.inputs)).comments.length, 0, 'Months have separate notes');
assert.equal(store.get(proposalKey(india.inputs)).versions.length, 0, 'Routes have separate versions');
store.addComment(november, 'November note only.');
assert.equal(store.get(key).comments.length, 1);
const reloaded = createProposalStore(storage, clock);
assert.deepEqual(reloaded.get(key), store.get(key), 'All local records survive reload');
assert.equal(reloaded.get(key).discussions.length, 2);
assert.equal(reloaded.get(key).discussions[1].role, 'assistant');
assert.equal(reloaded.get(key).discussions[1].source, 'ai', 'AI provenance survives reload');

const task = store.addTask(ctx, { title: 'Confirm bookings', owner: 'Airline planning team', dueDate: '2026-11-03', check: 'demand' });
assert.equal(priorityActions(ctx, store.get(key), clock()).rows[0].status, 'amber', 'A task is not evidence');
assert.throws(() => store.updateTask(ctx, task.id, 'verified', ''), /source/);
store.updateTask(ctx, task.id, 'waiting', 'Inquiry sent by the planner; response pending.');
assert.match(priorityActions(ctx, store.get(key), clock()).rows[0].reason, /Waiting/);
store.updateTask(ctx, task.id, 'verified', 'Airline forecast supplied on 1 November; occupancy and seats checked against this proposal.');
assert.equal(priorityActions(ctx, store.get(key), clock()).rows[0].status, 'green', 'Current evidence completes the check');
const changed = context({ ...inputs, extraFlights: 6 });
assert.equal(priorityActions(changed, store.get(key), clock()).rows[0].status, 'amber', 'Changing a plan invalidates verification');
assert.match(priorityActions(changed, store.get(key), clock()).rows[0].reason, /plan changed/);
assert.equal(priorityActions(changed, store.get(key), new Date('2026-11-04T12:00:00Z')).rows[0].status, 'red', 'Stale evidence cannot hide an overdue task');
assert.equal(priorityActions(ctx, store.get(key), new Date('2026-11-04T12:00:00Z')).rows[0].status, 'green', 'Valid completed checks do not become overdue');
const second = store.addTask(ctx, { title: 'Confirm aircraft', owner: 'Airline team', dueDate: '2026-11-02', check: 'demand' });
assert.equal(priorityActions(ctx, store.get(key), clock()).rows[0].status, 'amber', 'A completed task cannot hide another pending task');
assert.match(priorityActions(ctx, store.get(key), clock()).rows[0].reason, /1 action has evidence for the current plan. Remaining: 1 open action/);
store.updateTask(ctx, second.id, 'waiting', 'Awaiting the aircraft confirmation.');
const mixedWaiting = priorityActions(ctx, store.get(key), clock()).rows[0];
assert.equal(mixedWaiting.status, 'amber', 'Partial evidence stays amber while another response is pending');
assert.match(mixedWaiting.reason, /1 action has evidence for the current plan. Remaining: 1 action waiting for a response/);
assert.equal(mixedWaiting.evidence.length, 1);
assert.ok(!mixedWaiting.reason.includes('no verified evidence'), 'Mixed evidence must not be described as no evidence');
store.updateTask(ctx, second.id, 'verified', 'Aircraft schedule confirmed in airline plan dated 1 November.');
assert.equal(priorityActions(ctx, store.get(key), clock()).rows[0].status, 'green', 'All current verified actions complete the check');
const overdue = store.addTask(ctx, { title: 'Review planning note', owner: 'Proposal lead', dueDate: '2026-10-31', check: 'general' });
const priorities = priorityActions(ctx, store.get(key), clock());
assert.equal(priorities.recommended.id, `task:${overdue.id}`, 'An overdue general action takes priority');
assert.equal(priorities.recommended.owner, 'Proposal lead');
assert.equal(store.get(key).tasks[0].updates.length, 2, 'Every action update is retained');
assert.throws(() => store.addTask(ctx, { title: 'Test', owner: 'Team', dueDate: '2026-02-31', check: 'general' }), /valid due date/);
assert.throws(() => store.addTask(ctx, { title: 'Test', owner: '', dueDate: '2026-11-02', check: 'general' }), /owner/);
assert.throws(() => store.addDecision(ctx, 'Approved', 'This label is not supported'), /decision status/);

const newRoute = context({ ...inputs, originKey: 'GREECE', proxyOriginKey: 'ITALY' });
assert.match(priorityActions(newRoute, undefined, clock()).rows[0].reason, /not evidence of bookings/);
assert.ok(priorityActions(newRoute, undefined, clock()).rows[0].reason.includes(`${(inputs.loadFactor * 100).toFixed(1)}% full flights`), 'Demand check states the actual flight occupancy assumption');
const fewRecords = { ...ctx, result: { ...ctx.result, route: { ...ctx.result.route, yearsObserved: 1 } } };
assert.match(priorityActions(fewRecords, undefined, clock()).rows[0].reason, /Only 1 matching past flight record;/, 'Limited-history message reports the actual record count');
const highOccupancy = priorityActions(context({ ...inputs, loadFactor: 0.99 }), undefined, clock()).rows[0];
assert.equal(highOccupancy.status, 'amber', 'An occupancy assumption is not assigned an arbitrary red risk threshold');
assert.match(highOccupancy.reason, /99.0% full flights/);
const eventCheck = priorityActions(context({ ...inputs, eventUplift: 0.2 }), undefined, clock()).rows.find((row) => row.id === 'event');
assert.equal(eventCheck.status, 'amber');
assert.match(eventCheck.reason, /20.0% hotel demand/);
assert.match(eventCheck.reason, /not a measured event effect/);
assert.match(priorityActions(ctx, undefined, clock()).rows.find((row) => row.id === 'hotels').reason, /nights per stay/);
for (const kind of ['airline', 'hotel', 'team']) {
  const draft = stakeholderDraft(ctx, kind, store.get(key));
  assert.ok(draft.includes(ctx.decision.workplaceDecision.hotelNightsText));
  assert.match(draft, /France/);
  assert.match(draft, /December/);
  assert.match(draft, /Nothing has been sent/);
  assert.match(draft, /not occupied rooms/);
}
assert.match(stakeholderDraft(newRoute, 'airline'), /only starting points/);
const failing = createProposalStore({ getItem: () => null, setItem: () => { throw new Error('quota'); } }, clock);
failing.addComment(ctx, 'Kept in memory despite storage being full.');
assert.match(failing.warning, /could not save/);
assert.equal(failing.get(key).comments.length, 1);
const corrupt = createProposalStore({ getItem: () => '{bad data' }, clock);
assert.match(corrupt.warning, /could not be read/);
assert.equal(corrupt.get(key).tasks.length, 0);
const bounded = createProposalStore(null, clock);
for (let index = 0; index < 40; index++) bounded.saveVersion(ctx, `Version ${index}`);
assert.throws(() => bounded.saveVersion(ctx, 'Too many'), /versions limit/);
assert.equal(bounded.get(key).versions.length, 40, 'A limit never silently deletes saved history');
store.clearDiscussions(key);
assert.equal(store.get(key).discussions.length, 0);
assert.equal(store.get(key).comments.length, 1, 'Clearing chat keeps proposal notes');
assert.equal(store.get(key).versions.length, 1, 'Clearing chat keeps version snapshots');
// Exercise the factory's serialisation and integration contract without claiming
// a real browser interaction. The root app separately tests the rendered UI.
const uiMemory = new Map();
const uiStorage = { getItem: (name) => uiMemory.get(name), setItem: (name, value) => uiMemory.set(name, value) };
const testMount = () => ({ ownerDocument: { defaultView: { localStorage: uiStorage } }, innerHTML: '', addEventListener() {}, querySelectorAll: () => [], querySelector: () => null });
let active = ctx;
const mount = testMount();
const ui = createProposalWorkspace({ mount, chatEnabled: true, getContext: () => active });
ui.update(ctx);
const incoming = { role: 'bot', source: 'ai', text: 'An AI explanation for this proposal.' };
assert.equal(ui.recordDiscussion(incoming), true);
assert.ok(incoming.id, 'Main chat receives the persisted feedback identifier');
const reloadedUi = createProposalWorkspace({ mount: testMount(), getContext: () => active });
const restoredChat = reloadedUi.discussion();
assert.deepEqual(restoredChat.map(({ createdAt, ...entry }) => entry), [{ id: incoming.id, role: 'bot', source: 'ai', text: incoming.text, matchesCurrentPlan: true }]);
assert.ok(Number.isFinite(Date.parse(restoredChat[0].createdAt)), 'Reloaded chat preserves its recorded time');
active = context({ ...inputs, extraFlights: 6 });
assert.equal(reloadedUi.discussion()[0].matchesCurrentPlan, false, 'Earlier chat is labelled when assumptions change on the same route');
active = ctx;
assert.equal(reloadedUi.discussion()[0].matchesCurrentPlan, true, 'Returning to the exact assumptions restores the chat match');
const malicious = '<img src=x onerror="alert(1)"></textarea><script>alert(1)</script>';
ui.recordDiscussion({ role: 'user', text: malicious });
assert.ok(mount.innerHTML.includes('&lt;img'));
assert.ok(!mount.innerHTML.includes('<script>alert(1)</script>'), 'Chat text cannot introduce active HTML into the proposal workspace');
const pausedMount = testMount();
const pausedUi = createProposalWorkspace({ mount: pausedMount });
pausedUi.update(ctx);
assert.doesNotMatch(pausedMount.innerHTML, /Planning chat history/, 'Paused Chat has no transcript in Follow-ups');
assert.deepEqual(pausedUi.discussion(), ui.discussion(), 'Pausing Chat preserves saved conversations');
const backup = ui.exportLocalData();
backup.proposals[key].discussions[0].source = 'tampered';
assert.equal(ui.exportLocalData().proposals[key].discussions[0].source, 'ai', 'Exported JSON is a detached copy');
ui.update(null);
assert.match(mount.innerHTML, /Choose a valid plan/);
assert.equal(ui.contextSummary(), null, 'Invalid plan state cannot expose the previous proposal context');
active = november;
ui.update(november);
assert.deepEqual(ui.discussion(), [], 'Reload and route/month switching use the active proposal');
ui.clearDiscussion();
assert.equal(ui.exportLocalData().proposals[key].discussions.length, 2, 'Clearing another route cannot erase the original discussion');
const events = new Map();
const files = new Map();
const revoked = [];
let fileCount = 0;
const fileMount = testMount();
fileMount.addEventListener = (type, handler) => events.set(type, handler);
fileMount.ownerDocument.defaultView.Blob = Blob;
fileMount.ownerDocument.defaultView.URL = {
  createObjectURL: (blob) => { const url = `blob:proposal-test-${++fileCount}`; files.set(url, blob); return url; },
  revokeObjectURL: (url) => revoked.push(url),
};
fileMount.ownerDocument.body = { append() {} };
fileMount.ownerDocument.createElement = () => ({ click() {}, remove() {} });
const fileUi = createProposalWorkspace({ mount: fileMount, getContext: () => ctx });
fileUi.update(ctx);
await events.get('click')({ target: { closest: () => ({ dataset: { pwAction: 'backup' } }) } });
assert.match(fileMount.innerHTML, /id="pwDownloadReady" href="blob:proposal-test-1"/);
assert.match(fileMount.innerHTML, /History file ready/);
assert.deepEqual(JSON.parse(await files.get('blob:proposal-test-1').text()), fileUi.exportLocalData(), 'History download contains the exported proposal records');
fileUi.update(ctx);
assert.match(fileMount.innerHTML, /id="pwDownloadReady" href="blob:proposal-test-1"/, 'The ready-file link survives a normal rerender');
assert.deepEqual(revoked, [], 'A download URL remains available while its fallback link is shown');
await events.get('click')({ target: { closest: () => ({ dataset: { pwAction: 'backup' } }) } });
assert.deepEqual(revoked, ['blob:proposal-test-1'], 'Replacing a file releases the earlier download URL');
await events.get('click')({ target: { closest: () => ({ dataset: { pwAction: 'draft' } }) } });
const editedDraft = stakeholderDraft(ctx, 'airline') + '\nManual review note: please confirm the schedule.';
fileMount.querySelector = (selector) => selector === '[data-pw-draft]' ? { value: editedDraft } : null;
await events.get('click')({ target: { closest: () => ({ dataset: { pwAction: 'download-draft' } }) } });
assert.match(fileMount.innerHTML, /Draft file ready/);
assert.match(fileMount.innerHTML, /id="pwDownloadReady" href="blob:proposal-test-3" download="Air2Stay-France-December-airline-draft.txt"/);
assert.equal(await files.get('blob:proposal-test-3').text(), editedDraft, 'Draft download preserves the user-reviewed text');
fileUi.update(context({ ...inputs, extraFlights: 6 }));
assert.ok(!fileMount.innerHTML.includes('id="pwDownloadReady"'), 'Changing assumptions removes the old ready-file link');
assert.deepEqual(revoked, ['blob:proposal-test-1', 'blob:proposal-test-2', 'blob:proposal-test-3'], 'Changing assumptions revokes the old file URL');
await events.get('click')({ target: { closest: () => ({ dataset: { pwAction: 'backup' } }) } });
fileUi.update(india);
assert.ok(!fileMount.innerHTML.includes('id="pwDownloadReady"'), 'Changing country removes the earlier ready-file link');
await events.get('click')({ target: { closest: () => ({ dataset: { pwAction: 'backup' } }) } });
fileUi.dispose();
assert.deepEqual(revoked, ['blob:proposal-test-1', 'blob:proposal-test-2', 'blob:proposal-test-3', 'blob:proposal-test-4', 'blob:proposal-test-5'], 'Disposal releases the remaining download URL');
console.log('Proposal workspace checks passed: immutable snapshots, exact restoration, route/month isolation, persistence, RAG evidence, overdue/stale checks, drafts, bounds and failure handling.');
